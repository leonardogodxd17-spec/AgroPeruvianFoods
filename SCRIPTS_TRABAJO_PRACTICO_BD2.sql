-- 4.2 COMPILAR STORED PROCEDURE 02: Anulación y reposición de stock (RN-VNT-02)
-- [TOMAR CAPTURA 4.2: Compilación y ejecución de anulación]
CREATE OR REPLACE PROCEDURE SP_ANULAR_VENTA (
    p_id_venta IN NUMBER
) AS
    v_estado_actual VARCHAR2(20);
BEGIN
    SELECT ESTADO 
    INTO v_estado_actual
    FROM VENTAS 
    WHERE ID = p_id_venta 
    FOR UPDATE;

    IF v_estado_actual = 'ANULADA' THEN
        RAISE_APPLICATION_ERROR(-20015, 'La venta ya se encuentra anulada previamente.');
    END IF;

    -- Reponer inventario
    FOR item IN (SELECT ID_PRODUCTO, ID_LOTE, CANTIDAD FROM DETALLE_VENTAS WHERE ID_VENTA = p_id_venta) LOOP
        UPDATE PRODUCTOS 
        SET STOCK = STOCK + item.CANTIDAD 
        WHERE ID = item.ID_PRODUCTO;

        IF item.ID_LOTE IS NOT NULL THEN
            UPDATE LOTES_PRODUCTO 
            SET STOCK_DISPONIBLE = STOCK_DISPONIBLE + item.CANTIDAD 
            WHERE ID = item.ID_LOTE;
        END IF;
    END LOOP;

    UPDATE VENTAS 
    SET ESTADO = 'ANULADA' 
    WHERE ID = p_id_venta;

    COMMIT;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20016, 'No existe la venta indicada.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

