-- 5.1 COMPILAR FUNCIÓN 01: Determinar lote prioritario por vencimiento (FEFO)
-- [TOMAR CAPTURA 5.1: Compilación de FN_OBTENER_LOTE_FEFO]
CREATE OR REPLACE FUNCTION FN_OBTENER_LOTE_FEFO (
    p_id_producto IN NUMBER,
    p_cantidad    IN NUMBER
) RETURN VARCHAR2 AS
    v_codigo_lote VARCHAR2(30);
BEGIN
    SELECT CODIGO_LOTE
    INTO v_codigo_lote
    FROM (
        SELECT CODIGO_LOTE
        FROM LOTES_PRODUCTO
        WHERE ID_PRODUCTO = p_id_producto
          AND STOCK_DISPONIBLE >= p_cantidad
        ORDER BY FECHA_VENCIMIENTO ASC
    )
    WHERE ROWNUM = 1;

    RETURN v_codigo_lote;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 'SIN_LOTE_DISPONIBLE';
END;
