    FN_OBTENER_LOTE_FEFO(p.ID, 10) AS LOTE_PRIORITARIO_FEFO
FROM PRODUCTOS p
WHERE p.ID IN (1, 6);


-- 5.2 COMPILAR FUNCIÓN 02: Reporte de total recaudado por método de pago
-- [TOMAR CAPTURA 5.2: Compilación de FN_TOTAL_VENTAS_METODO]
CREATE OR REPLACE FUNCTION FN_TOTAL_VENTAS_METODO (
    p_metodo_pago IN VARCHAR2
) RETURN NUMBER AS
    v_total NUMBER(12, 2) := 0;
BEGIN
    SELECT NVL(SUM(TOTAL), 0)
    INTO v_total
    FROM VENTAS
    WHERE UPPER(METODO_PAGO) = UPPER(p_metodo_pago)
      AND ESTADO = 'REGISTRADA';

    RETURN v_total;
END;
/

-- PRUEBA DE LA FUNCIÓN 02:
-- [TOMAR CAPTURA 5.2 (Prueba): Resultados consolidados en DUAL]
SELECT 
    FN_TOTAL_VENTAS_METODO('EFECTIVO') AS RECAUDADO_EFECTIVO,
    FN_TOTAL_VENTAS_METODO('YAPE') AS RECAUDADO_YAPE,
    FN_TOTAL_VENTAS_METODO('TRANSFERENCIA') AS RECAUDADO_TRANSFERENCIA
FROM DUAL;
