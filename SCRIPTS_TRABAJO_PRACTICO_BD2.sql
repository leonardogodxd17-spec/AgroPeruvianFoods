-- 4.1 COMPILAR STORED PROCEDURE 01: Venta con regla de stock atómico (RN-VNT-01)
-- [TOMAR CAPTURA 4.1: Mensaje "Procedure SP_REGISTRAR_VENTA_ITEM compilado"]
CREATE OR REPLACE PROCEDURE SP_REGISTRAR_VENTA_ITEM (
    p_cliente_nombre IN VARCHAR2,
    p_metodo_pago    IN VARCHAR2,
    p_id_producto    IN NUMBER,
    p_id_lote        IN NUMBER DEFAULT NULL,
    p_cantidad       IN NUMBER,
    p_numero_ticket  OUT VARCHAR2,
    p_total_cobrado  OUT NUMBER
) AS
    v_stock_actual   NUMBER(10);
    v_precio_prod    NUMBER(10, 2);
    v_nombre_prod    VARCHAR2(120);
    v_subtotal_item  NUMBER(12, 2);
    v_igv            NUMBER(12, 2);
    v_base_neta      NUMBER(12, 2);
    v_id_venta       NUMBER;
BEGIN
    -- Validación de método de pago
    IF UPPER(p_metodo_pago) NOT IN ('EFECTIVO', 'YAPE', 'PLIN', 'TRANSFERENCIA') THEN
        RAISE_APPLICATION_ERROR(-20011, 'Método de pago no válido.');
    END IF;

    -- Bloqueo pesimista concurrente
    SELECT STOCK, PRECIO, NOMBRE 
    INTO v_stock_actual, v_precio_prod, v_nombre_prod
    FROM PRODUCTOS 
    WHERE ID = p_id_producto 
    FOR UPDATE;

    -- RN-VNT-01: Evitar sobreventa / stock negativo
    IF v_stock_actual < p_cantidad THEN
        RAISE_APPLICATION_ERROR(-20010, 
            'Regla RN-VNT-01: Stock insuficiente para ' || v_nombre_prod || 
            '. Disponible: ' || v_stock_actual || ' unidades.');
    END IF;

    -- Cálculos tributarios y comerciales
    v_subtotal_item := v_precio_prod * p_cantidad;
    v_igv := ROUND(v_subtotal_item * 0.18, 2);
    v_base_neta := v_subtotal_item - v_igv;
    p_numero_ticket := 'TKT-' || TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS');
    p_total_cobrado := v_subtotal_item;

    -- Registrar venta cabecera
    INSERT INTO VENTAS (NUMERO_TICKET, FECHA, ESTADO, METODO_PAGO, SUBTOTAL, IGV, TOTAL, CLIENTE_NOMBRE)
    VALUES (p_numero_ticket, SYSDATE, 'REGISTRADA', UPPER(p_metodo_pago), v_base_neta, v_igv, v_subtotal_item, p_cliente_nombre)
    RETURNING ID INTO v_id_venta;

    -- Registrar detalle de venta
    INSERT INTO DETALLE_VENTAS (ID_VENTA, ID_PRODUCTO, ID_LOTE, NOMBRE_PRODUCTO, PRECIO_UNITARIO, CANTIDAD, SUBTOTAL)
    VALUES (v_id_venta, p_id_producto, p_id_lote, v_nombre_prod, v_precio_prod, p_cantidad, v_subtotal_item);

    -- Descontar stock catálogo
    UPDATE PRODUCTOS 
    SET STOCK = STOCK - p_cantidad
    WHERE ID = p_id_producto;

    -- Descontar stock lote si aplica
    IF p_id_lote IS NOT NULL THEN
        UPDATE LOTES_PRODUCTO
        SET STOCK_DISPONIBLE = STOCK_DISPONIBLE - p_cantidad
        WHERE ID = p_id_lote;
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
