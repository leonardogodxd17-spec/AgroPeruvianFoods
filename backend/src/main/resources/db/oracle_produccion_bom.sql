-- 1. TABLA: TBL_INSUMOS (Materias primas y materiales de empaque)
CREATE TABLE TBL_INSUMOS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(40) NOT NULL UNIQUE,
    NOMBRE VARCHAR2(150) NOT NULL,
    UNIDAD_MEDIDA VARCHAR2(20) NOT NULL,
    COSTO_UNITARIO NUMBER(12, 4) NOT NULL,
    STOCK_ACTUAL NUMBER(12, 2) NOT NULL,
    STOCK_MINIMO NUMBER(12, 2) NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_INSUMO_UNIDAD CHECK (UNIDAD_MEDIDA IN ('UNIDAD', 'KG', 'LITRO')),
    CONSTRAINT CK_INSUMO_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE INDEX IDX_INSUMOS_CODIGO ON TBL_INSUMOS (CODIGO);
COMMENT ON TABLE TBL_INSUMOS IS 'Catálogo maestro de insumos, materias primas agrícolas y materiales de empaque';

-- 2. TABLA: TBL_RECETAS_BOM (Cabecera de Ficha Técnica / Bill of Materials)
CREATE TABLE TBL_RECETAS_BOM (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO_RECETA VARCHAR2(40) NOT NULL UNIQUE,
    PRODUCTO_ID NUMBER NOT NULL,
    PRODUCTO_NOMBRE VARCHAR2(150),
    NOMBRE_VERSION VARCHAR2(100) NOT NULL,
    COSTO_MANO_OBRA_ESTIMADO NUMBER(12, 2) NOT NULL,
    COSTO_TOTAL_PRODUCCION NUMBER(12, 2) NOT NULL,
    VIGENTE NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_RECETA_VIGENTE CHECK (VIGENTE IN (0, 1)),
    CONSTRAINT FK_RECETA_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES PRODUCTOS (ID)
);

CREATE INDEX IDX_RECETAS_PRODUCTO ON TBL_RECETAS_BOM (PRODUCTO_ID);
COMMENT ON TABLE TBL_RECETAS_BOM IS 'Cabecera de ficha técnica de producción con costeo de mano de obra y materiales';

-- 3. TABLA: TBL_DETALLES_RECETA_INSUMO (Detalle de Insumos por Receta)
CREATE TABLE TBL_DETALLES_RECETA_INSUMO (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RECETA_BOM_ID NUMBER NOT NULL,
    INSUMO_ID NUMBER NOT NULL,
    CANTIDAD_REQUERIDA NUMBER(12, 4) NOT NULL,
    COSTO_SUBTOTAL NUMBER(12, 4) NOT NULL,
    CONSTRAINT FK_DET_RECETA FOREIGN KEY (RECETA_BOM_ID) REFERENCES TBL_RECETAS_BOM (ID) ON DELETE CASCADE,
    CONSTRAINT FK_DET_INSUMO FOREIGN KEY (INSUMO_ID) REFERENCES TBL_INSUMOS (ID)
);

CREATE INDEX IDX_DET_RECETA_ID ON TBL_DETALLES_RECETA_INSUMO (RECETA_BOM_ID);
CREATE INDEX IDX_DET_INSUMO_ID ON TBL_DETALLES_RECETA_INSUMO (INSUMO_ID);
COMMENT ON TABLE TBL_DETALLES_RECETA_INSUMO IS 'Líneas de insumos y cantidades requeridas por unidad de producto terminado';

-- 4. TABLA: TBL_ORDENES_PRODUCCION (Cabecera de Órdenes de Trabajo)
CREATE TABLE TBL_ORDENES_PRODUCCION (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO_ORDEN VARCHAR2(40) NOT NULL UNIQUE,
    PRODUCTO_ID NUMBER NOT NULL,
    PRODUCTO_NOMBRE VARCHAR2(150),
    RECETA_BOM_ID NUMBER NOT NULL,
    CANTIDAD_A_PRODUCIR NUMBER(12, 2) NOT NULL,
    LOTE_GENERADO_ID NUMBER,
    CODIGO_LOTE_GENERADO VARCHAR2(50),
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FECHA_FINALIZACION TIMESTAMP,
    ESTADO VARCHAR2(30) NOT NULL,
    OBSERVACIONES VARCHAR2(500),
    CONSTRAINT CK_ORDEN_ESTADO CHECK (ESTADO IN ('PLANIFICADA', 'EN_PROCESO', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT FK_ORDEN_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES PRODUCTOS (ID),
    CONSTRAINT FK_ORDEN_RECETA FOREIGN KEY (RECETA_BOM_ID) REFERENCES TBL_RECETAS_BOM (ID)
);

CREATE INDEX IDX_ORDEN_ESTADO ON TBL_ORDENES_PRODUCCION (ESTADO);
CREATE INDEX IDX_ORDEN_FECHA ON TBL_ORDENES_PRODUCCION (FECHA_REGISTRO);
COMMENT ON TABLE TBL_ORDENES_PRODUCCION IS 'Órdenes de fabricación ejecutadas en planta para elaboración de lotes comerciales';

-- 5. TABLA: TBL_DETALLES_CONSUMO_INSUMO (Detalle Real de Insumos Consumidos)
CREATE TABLE TBL_DETALLES_CONSUMO_INSUMO (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDEN_PRODUCCION_ID NUMBER NOT NULL,
    INSUMO_ID NUMBER NOT NULL,
    CANTIDAD_CONSUMIDA NUMBER(12, 4) NOT NULL,
    COSTO_UNITARIO NUMBER(12, 4) NOT NULL,
    CONSTRAINT FK_DET_CONSUMO_ORDEN FOREIGN KEY (ORDEN_PRODUCCION_ID) REFERENCES TBL_ORDENES_PRODUCCION (ID) ON DELETE CASCADE,
    CONSTRAINT FK_DET_CONSUMO_INSUMO FOREIGN KEY (INSUMO_ID) REFERENCES TBL_INSUMOS (ID)
);

CREATE INDEX IDX_CONSUMO_ORDEN_ID ON TBL_DETALLES_CONSUMO_INSUMO (ORDEN_PRODUCCION_ID);
COMMENT ON TABLE TBL_DETALLES_CONSUMO_INSUMO IS 'Registro trazable de materias primas y empaques consumidos al finalizar la orden';
