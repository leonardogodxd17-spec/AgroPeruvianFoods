-- ESQUEMA 1: CATÁLOGO (PRODUCTO Y CATEGORÍA)
CREATE TABLE BOM_CATALOGO.CATEGORIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(80 BYTE) NOT NULL CONSTRAINT UQ_CATEGORIA_NOMBRE UNIQUE,
    DESCRIPCION VARCHAR2(200 BYTE)
);

CREATE TABLE BOM_CATALOGO.PRODUCTOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(120 BYTE) NOT NULL,
    PRECIO NUMBER(10, 2) NOT NULL CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO > 0),
    STOCK NUMBER(10) DEFAULT 0 NOT NULL CONSTRAINT CK_PRODUCTO_STOCK CHECK (STOCK >= 0),
    ID_CATEGORIA NUMBER,
    CONSTRAINT FK_PROD_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES BOM_CATALOGO.CATEGORIAS(ID)
);

CREATE INDEX BOM_CATALOGO.IDX_PROD_CATEGORIA ON BOM_CATALOGO.PRODUCTOS(ID_CATEGORIA);
CREATE INDEX BOM_CATALOGO.IDX_PROD_NOMBRE ON BOM_CATALOGO.PRODUCTOS(NOMBRE);


-- ESQUEMA 2: COMPRAS (PROVEEDORES Y COMPRAS CABECERA-DETALLE)
CREATE TABLE BOM_COMPRAS.PROVEEDORES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUC VARCHAR2(11 BYTE) NOT NULL CONSTRAINT UQ_PROVEEDOR_RUC UNIQUE,
    RAZON_SOCIAL VARCHAR2(150 BYTE) NOT NULL,
    TELEFONO VARCHAR2(20 BYTE),
    EMAIL VARCHAR2(80 BYTE),
    DIRECCION VARCHAR2(200 BYTE)
);

CREATE TABLE BOM_COMPRAS.COMPRAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_COMPROBANTE VARCHAR2(30 BYTE) NOT NULL,
    ID_PROVEEDOR NUMBER NOT NULL,
    FECHA_EMISION DATE NOT NULL,
    ESTADO VARCHAR2(20 BYTE) NOT NULL CONSTRAINT CK_COMPRA_ESTADO CHECK (ESTADO IN ('REGISTRADA', 'PAGADA', 'ANULADA')),
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    IGV NUMBER(12, 2) NOT NULL,
    TOTAL NUMBER(12, 2) NOT NULL CONSTRAINT CK_COMPRA_TOTAL CHECK (TOTAL >= 0),
    SALDO_PENDIENTE NUMBER(12, 2) NOT NULL CONSTRAINT CK_COMPRA_SALDO CHECK (SALDO_PENDIENTE >= 0),
    CONSTRAINT FK_COMPRA_PROVEEDOR FOREIGN KEY (ID_PROVEEDOR) REFERENCES BOM_COMPRAS.PROVEEDORES(ID)
);

CREATE TABLE BOM_COMPRAS.DETALLE_COMPRAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_COMPRA NUMBER NOT NULL,
    ID_INSUMO NUMBER NOT NULL,
    NOMBRE_INSUMO VARCHAR2(120 BYTE) NOT NULL,
    CANTIDAD NUMBER(12, 3) NOT NULL CONSTRAINT CK_DET_COMPRA_CANT CHECK (CANTIDAD > 0),
    PRECIO_UNITARIO NUMBER(10, 2) NOT NULL CONSTRAINT CK_DET_COMPRA_PRECIO CHECK (PRECIO_UNITARIO > 0),
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    CONSTRAINT FK_DET_COMPRA_CABECERA FOREIGN KEY (ID_COMPRA) REFERENCES BOM_COMPRAS.COMPRAS(ID) ON DELETE CASCADE
);

CREATE INDEX BOM_COMPRAS.IDX_COMPRA_PROVEEDOR ON BOM_COMPRAS.COMPRAS(ID_PROVEEDOR);
CREATE INDEX BOM_COMPRAS.IDX_COMPRA_FECHA ON BOM_COMPRAS.COMPRAS(FECHA_EMISION);


-- ESQUEMA 3: CAJA CHICA Y MOVIMIENTOS
CREATE TABLE BOM_CAJA.SESIONES_CAJA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CAJERO_NOMBRE VARCHAR2(100 BYTE) NOT NULL,
    FECHA_APERTURA TIMESTAMP NOT NULL,
    FECHA_CIERRE TIMESTAMP,
    MONTO_APERTURA NUMBER(12, 2) NOT NULL CONSTRAINT CK_CAJA_MONTO_AP CHECK (MONTO_APERTURA >= 0),
    MONTO_CIERRE NUMBER(12, 2),
    SALDO_TEORICO NUMBER(12, 2) NOT NULL,
    SALDO_REAL NUMBER(12, 2),
    DIFERENCIA NUMBER(12, 2),
    ESTADO VARCHAR2(20 BYTE) NOT NULL CONSTRAINT CK_CAJA_ESTADO CHECK (ESTADO IN ('ABIERTA', 'CERRADA')),
    OBSERVACIONES VARCHAR2(300 BYTE)
);

CREATE TABLE BOM_CAJA.MOVIMIENTOS_CAJA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_SESION_CAJA NUMBER NOT NULL,
    TIPO VARCHAR2(20 BYTE) NOT NULL CONSTRAINT CK_MOV_TIPO CHECK (TIPO IN ('INGRESO', 'EGRESO')),
    MONTO NUMBER(12, 2) NOT NULL CONSTRAINT CK_MOV_MONTO CHECK (MONTO > 0),
    CONCEPTO VARCHAR2(200 BYTE) NOT NULL,
    METODO_PAGO VARCHAR2(30 BYTE) NOT NULL CONSTRAINT CK_MOV_PAGO CHECK (METODO_PAGO IN ('EFECTIVO', 'YAPE', 'PLIN', 'TRANSFERENCIA')),
    REFERENCIA VARCHAR2(100 BYTE),
    FECHA TIMESTAMP NOT NULL,
    CONSTRAINT FK_MOV_SESION_CAJA FOREIGN KEY (ID_SESION_CAJA) REFERENCES BOM_CAJA.SESIONES_CAJA(ID)
);

CREATE INDEX BOM_CAJA.IDX_MOV_SESION ON BOM_CAJA.MOVIMIENTOS_CAJA(ID_SESION_CAJA);


-- ESQUEMA 4: PRODUCCIÓN Y CONTROL DE LOTES (CRITERIO FEFO)
CREATE TABLE BOM_PRODUCCION.ORDENES_PRODUCCION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_ORDEN VARCHAR2(30 BYTE) NOT NULL CONSTRAINT UQ_OP_CODIGO UNIQUE,
    ID_PRODUCTO NUMBER NOT NULL,
    NOMBRE_PRODUCTO VARCHAR2(120 BYTE) NOT NULL,
    CANTIDAD_PROGRAMADA NUMBER(10) NOT NULL CONSTRAINT CK_OP_CANT_PROG CHECK (CANTIDAD_PROGRAMADA > 0),
    CANTIDAD_PRODUCIDA NUMBER(10),
    FECHA_INICIO TIMESTAMP NOT NULL,
    FECHA_FIN TIMESTAMP,
    ESTADO VARCHAR2(20 BYTE) NOT NULL CONSTRAINT CK_OP_ESTADO CHECK (ESTADO IN ('PLANIFICADA', 'EN_PROCESO', 'COMPLETADA', 'CANCELADA')),
    OBSERVACIONES VARCHAR2(300 BYTE)
);

CREATE TABLE BOM_PRODUCCION.DETALLES_CONSUMO_INSUMO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ORDEN_PRODUCCION NUMBER NOT NULL,
    ID_INSUMO NUMBER NOT NULL,
    NOMBRE_INSUMO VARCHAR2(120 BYTE) NOT NULL,
    CANTIDAD_REQUERIDA NUMBER(12, 3) NOT NULL CONSTRAINT CK_DET_REQ CHECK (CANTIDAD_REQUERIDA > 0),
    CANTIDAD_CONSUMIDA NUMBER(12, 3) NOT NULL,
    UNIDAD_MEDIDA VARCHAR2(20 BYTE) NOT NULL,
    CONSTRAINT FK_DET_OP FOREIGN KEY (ID_ORDEN_PRODUCCION) REFERENCES BOM_PRODUCCION.ORDENES_PRODUCCION(ID) ON DELETE CASCADE
);

CREATE TABLE BOM_PRODUCCION.LOTES_PRODUCTO (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_LOTE VARCHAR2(30 BYTE) NOT NULL CONSTRAINT UQ_LOTE_CODIGO UNIQUE,
    ID_PRODUCTO NUMBER NOT NULL,
    NOMBRE_PRODUCTO VARCHAR2(120 BYTE) NOT NULL,
    STOCK_DISPONIBLE NUMBER(10) NOT NULL CONSTRAINT CK_LOTE_STOCK CHECK (STOCK_DISPONIBLE >= 0),
    FECHA_PRODUCCION DATE NOT NULL,
    FECHA_VENCIMIENTO DATE NOT NULL,
    CONSTRAINT CK_LOTE_FECHAS CHECK (FECHA_VENCIMIENTO >= FECHA_PRODUCCION)
);

CREATE INDEX BOM_PRODUCCION.IDX_LOTE_FEFO ON BOM_PRODUCCION.LOTES_PRODUCTO(ID_PRODUCTO, FECHA_VENCIMIENTO ASC);


-- ESQUEMA 5: VENTAS CABECERA-DETALLE
CREATE TABLE BOM_VENTAS.VENTAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_TICKET VARCHAR2(30 BYTE) NOT NULL CONSTRAINT UQ_VENTA_TICKET UNIQUE,
    FECHA TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20 BYTE) NOT NULL CONSTRAINT CK_VENTA_ESTADO CHECK (ESTADO IN ('REGISTRADA', 'ANULADA')),
    METODO_PAGO VARCHAR2(30 BYTE) NOT NULL CONSTRAINT CK_VENTA_PAGO CHECK (METODO_PAGO IN ('EFECTIVO', 'YAPE', 'PLIN', 'TRANSFERENCIA')),
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    IGV NUMBER(12, 2) NOT NULL,
    TOTAL NUMBER(12, 2) NOT NULL CONSTRAINT CK_VENTA_TOTAL CHECK (TOTAL >= 0),
    CLIENTE_NOMBRE VARCHAR2(120 BYTE)
);

CREATE TABLE BOM_VENTAS.DETALLE_VENTAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VENTA NUMBER NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    ID_LOTE NUMBER,
    NOMBRE_PRODUCTO VARCHAR2(120 BYTE) NOT NULL,
    PRECIO_UNITARIO NUMBER(10, 2) NOT NULL CONSTRAINT CK_DET_PRECIO CHECK (PRECIO_UNITARIO > 0),
    CANTIDAD NUMBER(10) NOT NULL CONSTRAINT CK_DET_CANTIDAD CHECK (CANTIDAD > 0),
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    CONSTRAINT FK_DET_VENTA FOREIGN KEY (ID_VENTA) REFERENCES BOM_VENTAS.VENTAS(ID) ON DELETE CASCADE
);

CREATE INDEX BOM_VENTAS.IDX_VENTA_FECHA ON BOM_VENTAS.VENTAS(FECHA);
CREATE INDEX BOM_VENTAS.IDX_VENTA_ESTADO ON BOM_VENTAS.VENTAS(ESTADO);
