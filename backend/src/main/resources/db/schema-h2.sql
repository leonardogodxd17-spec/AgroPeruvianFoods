CREATE SCHEMA IF NOT EXISTS BOM_CATALOGO;
CREATE SCHEMA IF NOT EXISTS BOM_COMPRAS;
CREATE SCHEMA IF NOT EXISTS BOM_CAJA;
CREATE SCHEMA IF NOT EXISTS BOM_PRODUCCION;
CREATE SCHEMA IF NOT EXISTS BOM_VENTAS;

-- CATÁLOGO
CREATE TABLE IF NOT EXISTS BOM_CATALOGO.CATEGORIAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR(80) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS BOM_CATALOGO.PRODUCTOS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR(120) NOT NULL,
    PRECIO DECIMAL(10, 2) NOT NULL,
    STOCK INT NOT NULL DEFAULT 0,
    ID_CATEGORIA BIGINT,
    FOREIGN KEY (ID_CATEGORIA) REFERENCES BOM_CATALOGO.CATEGORIAS(ID)
);

-- COMPRAS
CREATE TABLE IF NOT EXISTS BOM_COMPRAS.PROVEEDORES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUC VARCHAR(11) NOT NULL UNIQUE,
    RAZON_SOCIAL VARCHAR(150) NOT NULL,
    TELEFONO VARCHAR(20),
    EMAIL VARCHAR(80),
    DIRECCION VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS BOM_COMPRAS.COMPRAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_COMPROBANTE VARCHAR(30) NOT NULL,
    ID_PROVEEDOR BIGINT NOT NULL,
    FECHA_EMISION DATE NOT NULL,
    ESTADO VARCHAR(20) NOT NULL,
    SUBTOTAL DECIMAL(12, 2) NOT NULL,
    IGV DECIMAL(12, 2) NOT NULL,
    TOTAL DECIMAL(12, 2) NOT NULL,
    SALDO_PENDIENTE DECIMAL(12, 2) NOT NULL,
    FOREIGN KEY (ID_PROVEEDOR) REFERENCES BOM_COMPRAS.PROVEEDORES(ID)
);

CREATE TABLE IF NOT EXISTS BOM_COMPRAS.DETALLE_COMPRAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_COMPRA BIGINT NOT NULL,
    ID_INSUMO BIGINT NOT NULL,
    NOMBRE_INSUMO VARCHAR(120) NOT NULL,
    CANTIDAD DECIMAL(12, 3) NOT NULL,
    PRECIO_UNITARIO DECIMAL(10, 2) NOT NULL,
    SUBTOTAL DECIMAL(12, 2) NOT NULL,
    FOREIGN KEY (ID_COMPRA) REFERENCES BOM_COMPRAS.COMPRAS(ID) ON DELETE CASCADE
);

-- CAJA
CREATE TABLE IF NOT EXISTS BOM_CAJA.SESIONES_CAJA (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CAJERO_NOMBRE VARCHAR(100) NOT NULL,
    FECHA_APERTURA TIMESTAMP NOT NULL,
    FECHA_CIERRE TIMESTAMP,
    MONTO_APERTURA DECIMAL(12, 2) NOT NULL,
    MONTO_CIERRE DECIMAL(12, 2),
    SALDO_TEORICO DECIMAL(12, 2) NOT NULL,
    SALDO_REAL DECIMAL(12, 2),
    DIFERENCIA DECIMAL(12, 2),
    ESTADO VARCHAR(20) NOT NULL,
    OBSERVACIONES VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS BOM_CAJA.MOVIMIENTOS_CAJA (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_SESION_CAJA BIGINT NOT NULL,
    TIPO VARCHAR(20) NOT NULL,
    MONTO DECIMAL(12, 2) NOT NULL,
    CONCEPTO VARCHAR(200) NOT NULL,
    METODO_PAGO VARCHAR(30) NOT NULL,
    REFERENCIA VARCHAR(100),
    FECHA TIMESTAMP NOT NULL,
    FOREIGN KEY (ID_SESION_CAJA) REFERENCES BOM_CAJA.SESIONES_CAJA(ID)
);

-- PRODUCCIÓN
CREATE TABLE IF NOT EXISTS BOM_PRODUCCION.ORDENES_PRODUCCION (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_ORDEN VARCHAR(30) NOT NULL UNIQUE,
    ID_PRODUCTO BIGINT NOT NULL,
    NOMBRE_PRODUCTO VARCHAR(120) NOT NULL,
    CANTIDAD_PROGRAMADA INT NOT NULL,
    CANTIDAD_PRODUCIDA INT,
    FECHA_INICIO TIMESTAMP NOT NULL,
    FECHA_FIN TIMESTAMP,
    ESTADO VARCHAR(20) NOT NULL,
    OBSERVACIONES VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS BOM_PRODUCCION.DETALLES_CONSUMO_INSUMO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ORDEN_PRODUCCION BIGINT NOT NULL,
    ID_INSUMO BIGINT NOT NULL,
    NOMBRE_INSUMO VARCHAR(120) NOT NULL,
    CANTIDAD_REQUERIDA DECIMAL(12, 3) NOT NULL,
    CANTIDAD_CONSUMIDA DECIMAL(12, 3) NOT NULL,
    UNIDAD_MEDIDA VARCHAR(20) NOT NULL,
    FOREIGN KEY (ID_ORDEN_PRODUCCION) REFERENCES BOM_PRODUCCION.ORDENES_PRODUCCION(ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS BOM_PRODUCCION.LOTES_PRODUCTO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_LOTE VARCHAR(30) NOT NULL UNIQUE,
    ID_PRODUCTO BIGINT NOT NULL,
    NOMBRE_PRODUCTO VARCHAR(120) NOT NULL,
    STOCK_DISPONIBLE INT NOT NULL,
    FECHA_PRODUCCION DATE NOT NULL,
    FECHA_VENCIMIENTO DATE NOT NULL
);

-- VENTAS
CREATE TABLE IF NOT EXISTS BOM_VENTAS.VENTAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_TICKET VARCHAR(30) NOT NULL UNIQUE,
    FECHA TIMESTAMP NOT NULL,
    ESTADO VARCHAR(20) NOT NULL,
    METODO_PAGO VARCHAR(30) NOT NULL,
    SUBTOTAL DECIMAL(12, 2) NOT NULL,
    IGV DECIMAL(12, 2) NOT NULL,
    TOTAL DECIMAL(12, 2) NOT NULL,
    CLIENTE_NOMBRE VARCHAR(120)
);

CREATE TABLE IF NOT EXISTS BOM_VENTAS.DETALLE_VENTAS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_VENTA BIGINT NOT NULL,
    ID_PRODUCTO BIGINT NOT NULL,
    ID_LOTE BIGINT,
    NOMBRE_PRODUCTO VARCHAR(120) NOT NULL,
    PRECIO_UNITARIO DECIMAL(10, 2) NOT NULL,
    CANTIDAD INT NOT NULL,
    SUBTOTAL DECIMAL(12, 2) NOT NULL,
    FOREIGN KEY (ID_VENTA) REFERENCES BOM_VENTAS.VENTAS(ID) ON DELETE CASCADE
);
