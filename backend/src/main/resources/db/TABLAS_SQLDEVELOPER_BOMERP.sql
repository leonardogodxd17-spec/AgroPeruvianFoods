-- 1.1. SUCURSALES / ESTABLECIMIENTOS (Tienda, Planta, Ferias)
CREATE TABLE SUCURSALES (
    id_sucursal         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR2(100) NOT NULL,
    direccion           VARCHAR2(200) NOT NULL,
    ciudad              VARCHAR2(60)  NOT NULL,
    telefono            VARCHAR2(25),
    estado              VARCHAR2(20)  DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT chk_sucursal_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

COMMENT ON TABLE SUCURSALES IS 'Sedes físicas, plantas de procesamiento y puntos de venta';

-- 1.2. ROLES DEL SISTEMA
CREATE TABLE ROLES (
    id_rol              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR2(50)  NOT NULL UNIQUE,
    descripcion         VARCHAR2(200)
);

COMMENT ON TABLE ROLES IS 'Perfiles de acceso y permisos dentro del ERP';

-- 1.3. USUARIOS OPERATIVOS Y ADMINISTRATIVOS
CREATE TABLE USUARIOS (
    id_usuario          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sucursal         NUMBER NOT NULL,
    nombre_completo     VARCHAR2(120) NOT NULL,
    dni                 VARCHAR2(15)  NOT NULL UNIQUE,
    usuario             VARCHAR2(50)  NOT NULL UNIQUE,
    password_hash       VARCHAR2(255) NOT NULL,
    estado              VARCHAR2(20)  DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT fk_usuario_sucursal FOREIGN KEY (id_sucursal) 
        REFERENCES SUCURSALES(id_sucursal),
    CONSTRAINT chk_usuario_estado CHECK (estado IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO'))
);

COMMENT ON TABLE USUARIOS IS 'Colaboradores, cajeros y administradores con credenciales';

-- 1.4. ASIGNACIÓN USUARIO - ROLES (RELACIÓN N:M)
CREATE TABLE USUARIO_ROLES (
