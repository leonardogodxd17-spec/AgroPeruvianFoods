-- 8.1. Consulta FEFO (Lotes ordenados por caducidad para despacho prioritario)
PROMPT >>> Consulta 1: Trazabilidad FEFO de Lotes y Dias para Vencer;
SELECT L.codigo_lote, P.nombre AS producto, L.stock_disponible,
       L.fecha_produccion, L.fecha_vencimiento,
       ROUND(L.fecha_vencimiento - SYSDATE) AS dias_para_caducar
FROM LOTES_PRODUCTO L
JOIN PRODUCTOS P ON L.id_producto = P.id_producto
ORDER BY L.fecha_vencimiento ASC;

-- 8.2. Consulta de Recetas Industriales BOM (Estructura de costos)
PROMPT >>> Consulta 2: Estructura de Recetas Industriales BOM y Costeo;
SELECT R.nombre_receta, I.nombre AS insumo_requerido, 
       D.cantidad_requerida, I.unidad_medida, D.costo_unitario,
       (D.cantidad_requerida * D.costo_unitario) AS costo_parcial
FROM RECETAS_BOM R
JOIN DETALLES_RECETA_BOM D ON R.id_receta = D.id_receta
JOIN INSUMOS I ON D.id_insumo = I.id_insumo;

-- 8.3. Consulta de Ventas Omnicanal y Tickets ESC/POS
PROMPT >>> Consulta 3: Ventas Omnicanal, Tickets Termicos y Delivery;
SELECT V.codigo_venta, T.razon_social AS cliente, S.nombre AS sucursal,
       V.total, V.metodo_pago, TK.codigo_ticket, TK.formato_impresion,
       NVL(D.estado_reparto, 'TIENDA / RETIRO') AS estado_despacho
FROM VENTAS V
JOIN TERCEROS T ON V.id_tercero = T.id_tercero
JOIN SUCURSALES S ON V.id_sucursal = S.id_sucursal
LEFT JOIN TICKETS_VENTA TK ON V.id_venta = TK.id_venta
LEFT JOIN DESPACHOS_DELIVERY D ON V.id_venta = D.id_venta;

