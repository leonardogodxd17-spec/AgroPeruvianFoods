    costo_unitario      NUMBER(12,4) NOT NULL,
    CONSTRAINT fk_detreceta_receta FOREIGN KEY (id_receta) 
        REFERENCES RECETAS_BOM(id_receta) ON DELETE CASCADE,
    CONSTRAINT fk_detreceta_insumo FOREIGN KEY (id_insumo) 
        REFERENCES INSUMOS(id_insumo),
    CONSTRAINT chk_detreceta_cant CHECK (cantidad_requerida > 0),
    CONSTRAINT chk_detreceta_costo CHECK (costo_unitario >= 0)
