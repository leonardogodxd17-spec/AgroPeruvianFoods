COMMENT ON TABLE DETALLES_RECETA_BOM IS 'Cantidades de insumos y envases consumidos por unidad de receta';

-- 4.5. ÓRDENES DE PRODUCCIÓN
CREATE TABLE ORDENES_PRODUCCION (
    id_orden            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
