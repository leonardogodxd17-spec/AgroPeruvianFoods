    CONSTRAINT chk_op_estado CHECK (estado IN ('PLANIFICADA', 'EN_PROCESO', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT chk_op_cant CHECK (cantidad_a_producir > 0)
);

COMMENT ON TABLE ORDENES_PRODUCCION IS 'Órdenes de fabricación ejecutadas en planta Lurín';

-- 4.6. DETALLES DE CONSUMO REAL DE INSUMOS
CREATE TABLE DETALLES_CONSUMO_INSUMO (
    id_consumo          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden            NUMBER NOT NULL,
    id_insumo           NUMBER NOT NULL,
    cantidad_consumida  NUMBER(12,4) NOT NULL,
    CONSTRAINT fk_detcons_orden FOREIGN KEY (id_orden) 
        REFERENCES ORDENES_PRODUCCION(id_orden) ON DELETE CASCADE,
    CONSTRAINT fk_detcons_insumo FOREIGN KEY (id_insumo) 
        REFERENCES INSUMOS(id_insumo),
    CONSTRAINT chk_detcons_cant CHECK (cantidad_consumida >= 0)
);

COMMENT ON TABLE DETALLES_CONSUMO_INSUMO IS 'Registro de mermas y consumo efectivo de insumos en la orden';

-- 4.7. LOTES DE PRODUCTO TERMINADO (Con fechas para algoritmo FEFO)
CREATE TABLE LOTES_PRODUCTO (
    id_lote             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto         NUMBER NOT NULL,
    id_orden            NUMBER,
    codigo_lote         VARCHAR2(50) NOT NULL UNIQUE,
    fecha_produccion    DATE DEFAULT SYSDATE NOT NULL,
    fecha_envasado      DATE DEFAULT SYSDATE NOT NULL,
    fecha_vencimiento   DATE NOT NULL,
    stock_disponible    NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_lote_producto FOREIGN KEY (id_producto) 
        REFERENCES PRODUCTOS(id_producto),
    CONSTRAINT fk_lote_orden FOREIGN KEY (id_orden) 
        REFERENCES ORDENES_PRODUCCION(id_orden) ON DELETE SET NULL,
    CONSTRAINT chk_lote_stock CHECK (stock_disponible >= 0),
    CONSTRAINT chk_lote_fechas CHECK (fecha_vencimiento >= fecha_produccion)
);

COMMENT ON TABLE LOTES_PRODUCTO IS 'Trazabilidad de lotes terminados con fechas para despacho prioritario FEFO';


