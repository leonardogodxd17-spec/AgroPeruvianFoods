-- 1. TABLA: TBL_TERCEROS (Directorio Maestro de Clientes y Proveedores)
CREATE TABLE TBL_TERCEROS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TIPO_DOCUMENTO VARCHAR2(20) NOT NULL,
    NUMERO_DOCUMENTO VARCHAR2(30) NOT NULL UNIQUE,
    RAZON_SOCIAL VARCHAR2(150) NOT NULL,
    TIPO_TERCERO VARCHAR2(20) NOT NULL,
    TELEFONO VARCHAR2(30),
    DIRECCION VARCHAR2(250),
    CORREO VARCHAR2(100),
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT CK_TERCERO_TIPO CHECK (TIPO_TERCERO IN ('CLIENTE', 'PROVEEDOR', 'AMBOS')),
    CONSTRAINT CK_TERCERO_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE INDEX IDX_TERCEROS_DOC ON TBL_TERCEROS (NUMERO_DOCUMENTO);
CREATE INDEX IDX_TERCEROS_TIPO ON TBL_TERCEROS (TIPO_TERCERO);
COMMENT ON TABLE TBL_TERCEROS IS 'Directorio central de empresas asociadas, proveedores agrícolas y clientes corporativos';

-- 2. TABLA: TBL_COMPRAS (Cabecera de Órdenes de Compra y Facturas de Insumos)
CREATE TABLE TBL_COMPRAS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO_COMPRA VARCHAR2(40) NOT NULL UNIQUE,
    PROVEEDOR_ID NUMBER NOT NULL,
    PROVEEDOR_NOMBRE VARCHAR2(150),
    NUMERO_COMPROBANTE VARCHAR2(50) NOT NULL,
    FECHA_COMPRA DATE DEFAULT SYSDATE NOT NULL,
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    IGV NUMBER(12, 2) NOT NULL,
    TOTAL NUMBER(12, 2) NOT NULL,
    ESTADO VARCHAR2(20) NOT NULL,
    METODO_PAGO VARCHAR2(30) NOT NULL,
    OBSERVACIONES VARCHAR2(500),
    CONSTRAINT CK_COMPRA_ESTADO CHECK (ESTADO IN ('REGISTRADA', 'RECIBIDA', 'ANULADA')),
    CONSTRAINT FK_COMPRA_PROVEEDOR FOREIGN KEY (PROVEEDOR_ID) REFERENCES TBL_TERCEROS (ID)
);

CREATE INDEX IDX_COMPRAS_FECHA ON TBL_COMPRAS (FECHA_COMPRA);
CREATE INDEX IDX_COMPRAS_PROVEEDOR ON TBL_COMPRAS (PROVEEDOR_ID);
COMMENT ON TABLE TBL_COMPRAS IS 'Cabecera de compras de insumos, materias primas y suministros de embalaje';

-- 3. TABLA: TBL_DETALLES_COMPRA (Líneas de Detalle de Insumos Comprados)
CREATE TABLE TBL_DETALLES_COMPRA (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    COMPRA_ID NUMBER NOT NULL,
    INSUMO_ID NUMBER NOT NULL,
    INSUMO_NOMBRE VARCHAR2(150),
    CANTIDAD NUMBER(12, 2) NOT NULL,
    PRECIO_UNITARIO NUMBER(12, 4) NOT NULL,
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    CONSTRAINT FK_DET_COMPRA_CAB FOREIGN KEY (COMPRA_ID) REFERENCES TBL_COMPRAS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_DET_COMPRA_INSUMO FOREIGN KEY (INSUMO_ID) REFERENCES TBL_INSUMOS (ID)
);

CREATE INDEX IDX_DET_COMPRA_ID ON TBL_DETALLES_COMPRA (COMPRA_ID);
COMMENT ON TABLE TBL_DETALLES_COMPRA IS 'Desglose de insumos recibidos con impacto directo en el costo ponderado de inventario';

-- 4. TABLA: TBL_PEDIDOS_DELIVERY (Seguimiento de Reparto y Envíos a Domicilio)
CREATE TABLE TBL_PEDIDOS_DELIVERY (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO_PEDIDO VARCHAR2(40) NOT NULL UNIQUE,
    VENTA_ID NUMBER,
    CLIENTE_ID NUMBER,
    CLIENTE_NOMBRE VARCHAR2(150) NOT NULL,
    CLIENTE_TELEFONO VARCHAR2(30),
    DIRECCION_ENTREGA VARCHAR2(250) NOT NULL,
    REFERENCIA VARCHAR2(250),
    COSTO_ENVIO NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    MONTO_TOTAL NUMBER(12, 2),
    REPARTIDOR_NOMBRE VARCHAR2(120),
    ESTADO_DELIVERY VARCHAR2(20) NOT NULL,
    FECHA_PACTADA TIMESTAMP,
    FECHA_ENTREGA TIMESTAMP,
    OBSERVACIONES VARCHAR2(500),
    CONSTRAINT CK_DELIVERY_ESTADO CHECK (ESTADO_DELIVERY IN ('PENDIENTE', 'EN_RUTA', 'ENTREGADO', 'CANCELADO')),
    CONSTRAINT FK_DELIVERY_VENTA FOREIGN KEY (VENTA_ID) REFERENCES TBL_VENTAS (ID) ON DELETE SET NULL,
    CONSTRAINT FK_DELIVERY_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES TBL_TERCEROS (ID) ON DELETE SET NULL
);

CREATE INDEX IDX_DELIVERY_ESTADO ON TBL_PEDIDOS_DELIVERY (ESTADO_DELIVERY);
CREATE INDEX IDX_DELIVERY_FECHA ON TBL_PEDIDOS_DELIVERY (FECHA_PACTADA);
COMMENT ON TABLE TBL_PEDIDOS_DELIVERY IS 'Despachos y monitoreo logístico de envíos a domicilio para clientes corporativos y particulares';
