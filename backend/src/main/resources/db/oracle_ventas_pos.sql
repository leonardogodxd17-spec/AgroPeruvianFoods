-- 1. TABLA: TBL_VENTAS
CREATE TABLE TBL_VENTAS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO_VENTA VARCHAR2(40) NOT NULL UNIQUE,
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CANAL VARCHAR2(30) NOT NULL,
    CLIENTE_TIPO VARCHAR2(30) NOT NULL,
    CLIENTE_NOMBRE VARCHAR2(150) NOT NULL,
    CLIENTE_NUMERO_DOC VARCHAR2(20),
    METODO_PAGO VARCHAR2(30) NOT NULL,
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    IGV NUMBER(12, 2) NOT NULL,
    TOTAL NUMBER(12, 2) NOT NULL,
    MONTO_PAGADO NUMBER(12, 2) NOT NULL,
    VUELTO NUMBER(12, 2) NOT NULL,
    SESION_CAJA_ID NUMBER,
    CAJERO_NOMBRE VARCHAR2(120),
    ESTADO VARCHAR2(20) NOT NULL,
    CONSTRAINT CK_VENTA_CANAL CHECK (CANAL IN ('TIENDA_MOSTRADOR', 'FERIA_COMERCIAL', 'DELIVERY')),
    CONSTRAINT CK_VENTA_METODO CHECK (METODO_PAGO IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA_DIGITAL')),
    CONSTRAINT CK_VENTA_ESTADO CHECK (ESTADO IN ('EMITIDA', 'ANULADA')),
    CONSTRAINT FK_VENTA_SESION FOREIGN KEY (SESION_CAJA_ID) REFERENCES SESIONES_CAJA (ID) ON DELETE SET NULL
);

CREATE INDEX IDX_VENTAS_FECHA ON TBL_VENTAS (FECHA_HORA);
CREATE INDEX IDX_VENTAS_SESION ON TBL_VENTAS (SESION_CAJA_ID);

COMMENT ON TABLE TBL_VENTAS IS 'Cabecera de transacciones comerciales del punto de venta mostrador y ferias';

-- 2. TABLA: TBL_DETALLES_VENTA
CREATE TABLE TBL_DETALLES_VENTA (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    VENTA_ID NUMBER NOT NULL,
    PRODUCTO_ID NUMBER NOT NULL,
    PRODUCTO_NOMBRE VARCHAR2(150) NOT NULL,
    CANTIDAD NUMBER(12, 2) NOT NULL,
    PRECIO_UNITARIO NUMBER(10, 2) NOT NULL,
    SUBTOTAL NUMBER(12, 2) NOT NULL,
    LOTES_CONSUMIDOS_FEFO VARCHAR2(350),
    CONSTRAINT FK_DETALLE_VENTA FOREIGN KEY (VENTA_ID) REFERENCES TBL_VENTAS (ID) ON DELETE CASCADE
);

CREATE INDEX IDX_DETALLE_VENTA_ID ON TBL_DETALLES_VENTA (VENTA_ID);

COMMENT ON TABLE TBL_DETALLES_VENTA IS 'Ítems individuales de la venta con detalle trazable de lotes FEFO consumidos';
