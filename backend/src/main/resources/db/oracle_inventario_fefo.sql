-- 1. TABLA: TBL_LOTES (Lotes de Producción y Vencimiento)
CREATE TABLE TBL_LOTES (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO_LOTE VARCHAR2(50) NOT NULL UNIQUE,
    PRODUCTO_ID NUMBER NOT NULL,
    PRODUCTO_NOMBRE VARCHAR2(150) NOT NULL,
    FECHA_FABRICACION DATE NOT NULL,
    FECHA_VENCIMIENTO DATE NOT NULL,
    STOCK_INICIAL NUMBER(12, 2) NOT NULL,
    STOCK_ACTUAL NUMBER(12, 2) NOT NULL,
    COSTO_UNITARIO NUMBER(10, 2) NOT NULL,
    ESTADO VARCHAR2(25) NOT NULL,
    OBSERVACIONES VARCHAR2(255),
    CONSTRAINT CK_LOTE_STOCK_ACTUAL CHECK (STOCK_ACTUAL >= 0),
    CONSTRAINT CK_LOTE_FECHAS CHECK (FECHA_VENCIMIENTO >= FECHA_FABRICACION),
    CONSTRAINT CK_LOTE_ESTADO CHECK (ESTADO IN ('DISPONIBLE', 'PROXIMO_A_VENCER', 'VENCIDO', 'AGOTADO'))
);

CREATE INDEX IDX_LOTES_FEFO ON TBL_LOTES (PRODUCTO_ID, ESTADO, FECHA_VENCIMIENTO);

COMMENT ON TABLE TBL_LOTES IS 'Almacén de lotes de producción para productos perecibles (cacao, aceite de coco) bajo regla FEFO';
COMMENT ON COLUMN TBL_LOTES.CODIGO_LOTE IS 'Código alfa-numérico único del lote (e.g. LOT-COCO500-2026-A1)';
COMMENT ON COLUMN TBL_LOTES.FECHA_VENCIMIENTO IS 'Criterio clave del orden de despacho FEFO (First Expired, First Out)';

-- 2. TABLA: TBL_MOVIMIENTOS_KARDEX (Trazabilidad y Auditoría de Movimientos)
CREATE TABLE TBL_MOVIMIENTOS_KARDEX (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TIPO VARCHAR2(20) NOT NULL,
    LOTE_ID NUMBER,
    PRODUCTO_ID NUMBER NOT NULL,
    PRODUCTO_NOMBRE VARCHAR2(150) NOT NULL,
    CANTIDAD NUMBER(12, 2) NOT NULL,
    SALDO_STOCK_RESULTANTE NUMBER(12, 2) NOT NULL,
    MOTIVO VARCHAR2(100) NOT NULL,
    DOCUMENTO_REFERENCIA VARCHAR2(100),
    FECHA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_KARDEX_LOTE FOREIGN KEY (LOTE_ID) REFERENCES TBL_LOTES (ID) ON DELETE SET NULL,
    CONSTRAINT CK_KARDEX_TIPO CHECK (TIPO IN ('ENTRADA', 'SALIDA', 'AJUSTE'))
);

CREATE INDEX IDX_KARDEX_PRODUCTO ON TBL_MOVIMIENTOS_KARDEX (PRODUCTO_ID, FECHA_HORA);
CREATE INDEX IDX_KARDEX_LOTE ON TBL_MOVIMIENTOS_KARDEX (LOTE_ID);

COMMENT ON TABLE TBL_MOVIMIENTOS_KARDEX IS 'Registro inmutable de entradas, salidas y ajustes de stock por lote en almacén';
